import re
from collections import defaultdict
from datetime import date
 
import streamlit as st
 
import db
from agent import DEPTH_STEPS, run_research
from theme import get_css, trace_table_html
 
try:
    from pdf_export import markdown_to_pdf
except ImportError:  # reportlab not installed
    markdown_to_pdf = None
 
st.set_page_config(page_title="Research Agent", page_icon="🔎", layout="wide")
db.init_db()
 
EXAMPLES = {
    "Digital rupee vs UPI": "Impact of RBI's digital rupee on UPI",
    "Nuclear energy in India": "Pros and cons of nuclear energy in India",
    "RAG and hallucinations": "How retrieval-augmented generation reduces hallucinations in LLMs",
}
 
 
def set_topic(topic: str):
    st.session_state.topic_input = topic
 
 
@st.cache_data(show_spinner=False)
def build_pdf(report: str, title: str) -> bytes:
    return markdown_to_pdf(
        report, title=title, subtitle=f"Generated by Research Agent · {date.today():%d %b %Y}"
    )
 
 
def show_run(run_id: int):
    run = db.get_run(run_id)
    if not run:
        st.warning("That run no longer exists.")
        return
    notes = db.get_notes(run_id)
    events = db.get_events(run_id)
    sources = {n["source"] for n in notes}
 
    st.subheader(f"Run #{run['id']}: {run['topic']}")
    c1, c2, c3, c4, c5 = st.columns(5)
    c1.metric("Status", run["status"])
    c2.metric("Steps", run["steps"])
    c3.metric("Notes saved", len(notes))
    c4.metric("Sources", len(sources))
    c5.metric("Time", f"{run['seconds']:.0f} s" if run["seconds"] is not None else "n/a")
 
    tab_report, tab_notes, tab_trace = st.tabs(["📄 Report", "📝 Notes & sources", "🔍 Agent trace"])
 
    with tab_report:
        if run["report"]:
            pdf_bytes = None
            if markdown_to_pdf is None:
                st.caption("PDF export needs one more package. Run: `pip install reportlab`")
            else:
                try:
                    pdf_bytes = build_pdf(run["report"], run["topic"])
                except Exception as e:
                    st.warning(f"Could not build the PDF: {e}")
 
            b1, b2, _ = st.columns([1, 1, 2])
            if pdf_bytes:
                b1.download_button(
                    "⬇️ Download PDF", pdf_bytes, file_name=f"report_{run['id']}.pdf",
                    mime="application/pdf", key=f"pdf_{run['id']}", use_container_width=True,
                )
            b2.download_button(
                "⬇️ Download Markdown", run["report"], file_name=f"report_{run['id']}.md",
                mime="text/markdown", key=f"md_{run['id']}", use_container_width=True,
            )
            st.markdown(run["report"])
        else:
            st.info("No report was saved for this run (it may have failed).")
 
    with tab_notes:
        if not notes:
            st.info("The agent did not save any notes.")
        grouped = defaultdict(list)
        for n in notes:
            grouped[n["sub_question"]].append(n)
        for question, items in grouped.items():
            st.markdown(f"**{question}**")
            for n in items:
                st.markdown(f"- {n['finding']}  \n  <{n['source']}>")
 
    with tab_trace:
        st.caption("Every tool call the agent made, in order. This shows how it reasoned.")
        if events:
            st.markdown(trace_table_html(events), unsafe_allow_html=True)
        else:
            st.info("No trace recorded for this run.")
 
 
# ---------------- Sidebar: theme + history ----------------
with st.sidebar:
    st.header("Settings")
    mode = st.radio(
        "Theme",
        ["Auto", "Light", "Dark"],
        key="theme_mode",
        horizontal=True,
        help="Auto follows your system or Streamlit's own theme setting.",
    )
 
    st.header("History")
    runs = db.list_runs(30)
    options = {f"#{r['id']} · {r['topic'][:32]} · {r['status']}": r["id"] for r in runs}
    default = 0
    for i, rid in enumerate(options.values(), start=1):
        if rid == st.session_state.get("view_run"):
            default = i
    choice = st.selectbox("Open a past run", ["-"] + list(options), index=default)
    view_id = options.get(choice)
    if view_id and st.button("🗑 Delete this run"):
        db.delete_run(view_id)
        st.session_state.pop("view_run", None)
        st.rerun()
    st.divider()
    st.caption("Quick mode uses fewer steps and finishes faster. Deep mode researches more thoroughly.")
    st.markdown(get_css(mode), unsafe_allow_html=True)
 
# ---------------- Main: new run ----------------
st.title("🔎 Autonomous Research Agent")
st.caption("Plans sub-questions, searches the web, reads sources, takes notes and writes a cited report.")
 
topic = st.text_input(
    "Research topic",
    key="topic_input",
    placeholder="e.g. Impact of RBI's digital rupee on UPI",
)
cols = st.columns(len(EXAMPLES))
for col, (label, full_topic) in zip(cols, EXAMPLES.items()):
    col.button(label, on_click=set_topic, args=(full_topic,), use_container_width=True)
 
depth = st.radio(
    "Depth",
    list(DEPTH_STEPS),
    horizontal=True,
    format_func=lambda d: f"{d} (up to {DEPTH_STEPS[d]} steps)",
)
 
if st.button("Run research", type="primary", disabled=not topic.strip()):
    max_steps = DEPTH_STEPS[depth]
    progress = st.progress(0.0, text="Starting...")
    log = st.status("Agent working...", expanded=True)
 
    def on_event(msg: str):
        log.write(msg)
        m = re.match(r"\[step (\d+)\]", msg)
        if m:
            step = int(m.group(1))
            progress.progress(min(step / max_steps, 1.0), text=f"Step {step} of up to {max_steps}")
 
    try:
        run_research(topic.strip(), depth, on_event)
    except Exception as e:
        log.update(label="Failed", state="error")
        st.error(f"Run failed: {e}")
    else:
        st.session_state.view_run = db.list_runs(1)[0]["id"]
        st.rerun()
 
st.divider()
if view_id:
    show_run(view_id)
else:
    st.info("Enter a topic above and click **Run research**, or open a past run from the sidebar.")
 